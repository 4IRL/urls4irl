from __future__ import annotations

from pathlib import Path

import pytest
from flask import Flask

from backend.api_common.error_codes_ts import generate_error_codes_ts

pytestmark = pytest.mark.cli


def test_generate_error_codes_cli_writes_typescript(app: Flask, tmp_path: Path):
    """
    GIVEN the `flask openapi generate-error-codes` CLI command
    WHEN invoked with --output pointing at a temp file path
    THEN it exits 0, echoes the write, and the file is non-empty with the banner
    """
    output_path = tmp_path / "error-codes.ts"
    result = app.test_cli_runner().invoke(
        args=["openapi", "generate-error-codes", "--output", str(output_path)]
    )

    assert result.exit_code == 0
    assert "openapi: wrote error codes" in result.output
    rendered = output_path.read_text(encoding="utf-8")
    assert rendered == generate_error_codes_ts()
    assert "// Generated by `flask openapi generate-error-codes`" in rendered


def test_generate_error_codes_cli_requires_output(app: Flask):
    """
    GIVEN the `flask openapi generate-error-codes` CLI command
    WHEN invoked without --output
    THEN it exits non-zero (click usage error)
    """
    result = app.test_cli_runner().invoke(args=["openapi", "generate-error-codes"])

    assert result.exit_code != 0
