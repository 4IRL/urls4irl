def _invoke_audit(
    cli_runner: FlaskCliRunner, registry_path: Path, markdown_path: Path, *flags: str
) -> Result:
    return cli_runner.invoke(
        args=[
            "endpoints",
            "audit",
            *flags,
            "--registry",
            str(registry_path),
            "--markdown",
            str(markdown_path),
        ]
    )


def test_audit_strict_exits_zero_on_committed_registry(runner):
    """
    GIVEN the committed docs/endpoints artifacts and the live app
    WHEN `flask endpoints audit --strict` runs
    THEN it exits 0 and every section prints `(none)`
    """
    app, cli_runner = runner

    result = _invoke_audit(cli_runner, COMMITTED_JSON, COMMITTED_MARKDOWN, "--strict")

    assert result.exit_code == 0, result.output
    lines = result.output.splitlines()
    for section in AUDIT_SECTIONS:
        assert lines[lines.index(section) + 1] == AUDIT_NONE_PLACEHOLDER


def test_audit_strict_fails_when_committed_registry_lacks_an_endpoint(runner, tmp_path):
    """
    GIVEN a copy of the committed JSON with one endpoint deleted
    WHEN `flask endpoints audit --strict` runs against the copy
    THEN it exits 1 and names the endpoint as missing_in_registry
    """
    app, cli_runner = runner
    registry = json.loads(COMMITTED_JSON.read_text(encoding="utf-8"))
    removed_endpoint = registry["endpoints"].pop(0)["endpoint"]
    registry_path = tmp_path / "endpoint-registry.json"
    registry_path.write_text(json.dumps(registry), encoding="utf-8")

    result = _invoke_audit(cli_runner, registry_path, COMMITTED_MARKDOWN, "--strict")

    assert result.exit_code == 1, result.output
    assert f"missing_in_registry\t{removed_endpoint}\t" in result.output


def test_audit_without_strict_reports_but_exits_zero(runner, tmp_path):
    """
    GIVEN a committed markdown copy with a hand edit
    WHEN `flask endpoints audit` runs without --strict
    THEN it exits 0 but still prints the markdown_stale finding
    """
    app, cli_runner = runner
    markdown_path = tmp_path / "ENDPOINT_REGISTRY.md"
    shutil.copyfile(COMMITTED_MARKDOWN, markdown_path)
    with markdown_path.open("a", encoding="utf-8") as markdown_file:
        markdown_file.write("hand edit\n")

    result = _invoke_audit(cli_runner, COMMITTED_JSON, markdown_path)

    assert result.exit_code == 0, result.output
    assert "markdown_stale\t*\trun make generate-endpoints" in result.output


@pytest.mark.parametrize(
    ("registry_contents", "expected_detail"),
    [
        pytest.param(None, "committed registry not found", id="missing"),
        pytest.param("{not json", "committed registry unreadable", id="invalid-json"),
        pytest.param("[]", "committed registry has an invalid shape", id="bad-shape"),
        pytest.param(
            '{"endpoints": ["not a row"]}',
            "committed registry has an invalid shape",
            id="non-dict-row",
        ),
    ],
)
def test_audit_unusable_committed_registry_is_a_single_finding(
    runner, tmp_path, registry_contents, expected_detail
):
    """
    GIVEN a committed registry path that is missing, not JSON, or the wrong shape
    WHEN `flask endpoints audit --strict` runs
    THEN it exits 1 with one missing_in_registry finding (no traceback) and
        skips the markdown comparison
    """
    app, cli_runner = runner
    registry_path = tmp_path / "endpoint-registry.json"
    if registry_contents is not None:
        registry_path.write_text(registry_contents, encoding="utf-8")

    result = _invoke_audit(cli_runner, registry_path, COMMITTED_MARKDOWN, "--strict")

    assert result.exit_code == 1, result.output
    assert result.exception is None or isinstance(result.exception, SystemExit)
    assert f"missing_in_registry\t*\t{expected_detail}" in result.output
    assert result.output.count("missing_in_registry") == 1
    lines = result.output.splitlines()
    markdown_index = lines.index(AUDIT_SECTION_MARKDOWN)
    assert lines[markdown_index + 1] == AUDIT_NONE_PLACEHOLDER


