def test_audit_strict_reports_stale_indirect_entry(runner, monkeypatch):
    """
    GIVEN an INDIRECT_JS_ENDPOINTS map that also names a dead endpoint
    WHEN `flask endpoints audit --strict` runs against the committed artifacts
    THEN it exits 1 and lists indirect_entry_unknown under the stale-entries
        section
    """
