pytestmark = pytest.mark.cli

DO_NOT_EDIT_HEADER = "<!-- Generated by `flask endpoints generate` — DO NOT EDIT. -->"
PROBE_ENDPOINT = "endpoints_cli_probe.probe_page"
PROBE_RULE = "/endpoints-cli-probe"

_REPO_ROOT = Path(__file__).resolve().parents[3]
COMMITTED_JSON = _REPO_ROOT / "docs" / "endpoints" / "endpoint-registry.json"
COMMITTED_MARKDOWN = _REPO_ROOT / "docs" / "endpoints" / "ENDPOINT_REGISTRY.md"
AUDIT_SECTIONS = (
    AUDIT_SECTION_DRIFT,
    AUDIT_SECTION_JS,
    AUDIT_SECTION_NO_JS,
    AUDIT_SECTION_MARKDOWN,
)

# Module-level so the registry's AST lookup can find the handler's `def`.
endpoints_cli_probe = Blueprint("endpoints_cli_probe", __name__)


@endpoints_cli_probe.route(PROBE_RULE, methods=["GET"])
def probe_page() -> str:
    return ""


def test_generate_writes_json_and_markdown(runner, tmp_path):
    """
    GIVEN a fully configured Flask app with all blueprints registered
    WHEN the developer runs `flask endpoints generate` with tmp output paths
    THEN it exits 0, the JSON parses with endpoints, and the markdown begins
        with the DO-NOT-EDIT comment
    """
    app, cli_runner = runner
    json_path = tmp_path / "x.json"
    markdown_path = tmp_path / "x.md"

    result = cli_runner.invoke(
        args=[
            "endpoints",
            "generate",
            "--output",
            str(json_path),
            "--markdown-output",
            str(markdown_path),
        ]
    )
    assert result.exit_code == 0, f"CLI failed: {result.output}"

    registry = json.loads(json_path.read_text(encoding="utf-8"))
    endpoint_count = len(registry["endpoints"])
    assert endpoint_count > 0
    assert f"wrote {endpoint_count} endpoints" in result.output
    assert markdown_path.read_text(encoding="utf-8").startswith(DO_NOT_EDIT_HEADER)


@pytest.mark.parametrize("bad_option", ["--output", "--markdown-output"])
def test_generate_to_nonexistent_directory_fails(runner, tmp_path, bad_option):
    """
    GIVEN a fully configured Flask app
    WHEN either output path points into a non-existent directory
    THEN exit_code != 0, the error names the missing directory and no file is
        written for the other (valid) path
    """
    app, cli_runner = runner
    missing_dir = tmp_path / "does_not_exist"
    paths = {
        "--output": tmp_path / "x.json",
        "--markdown-output": tmp_path / "x.md",
    }
    paths[bad_option] = missing_dir / "out"

    result = cli_runner.invoke(
        args=[
            "endpoints",
            "generate",
            "--output",
            str(paths["--output"]),
            "--markdown-output",
            str(paths["--markdown-output"]),
        ]
    )
    assert result.exit_code != 0
    assert "does not exist" in result.output.lower()
    assert str(missing_dir) in result.output
    assert not any(path.exists() for path in paths.values())


def _minimal_probe_app() -> Flask:
    """A DB-free Flask app with only the probe blueprint and the endpoints CLI."""
    minimal_app = Flask(__name__)
    minimal_app.register_blueprint(endpoints_cli_probe)
    register_endpoints_cli(minimal_app)
    return minimal_app


def test_generate_on_minimal_app_includes_probe_route(tmp_path):
    """
    GIVEN a DB-free minimal Flask app with one probe blueprint route
    WHEN the developer runs `flask endpoints generate`
    THEN the probe route appears in both the JSON and the markdown
    """
    minimal_app = _minimal_probe_app()
    json_path = tmp_path / "probe.json"
    markdown_path = tmp_path / "probe.md"

    result = minimal_app.test_cli_runner().invoke(
        args=[
            "endpoints",
            "generate",
            "--output",
            str(json_path),
            "--markdown-output",
            str(markdown_path),
        ]
    )
    assert result.exit_code == 0, f"CLI failed: {result.output}"

    registry = json.loads(json_path.read_text(encoding="utf-8"))
    assert [row["endpoint"] for row in registry["endpoints"]] == [PROBE_ENDPOINT]
    assert registry["endpoints"][0]["rule"] == PROBE_RULE
    assert f"### `GET {PROBE_RULE}` — `{PROBE_ENDPOINT}`" in markdown_path.read_text(
        encoding="utf-8"
    )


