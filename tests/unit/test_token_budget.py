def test_queues_behind_holder_and_kernel_releases_on_sigkill(
    tmp_path: Path, lock_dir: Path, spawn: Callable[..., Runner]
) -> None:
    holder_child, holder_started, _ = _marker_child(tmp_path, "holder")
    holder = spawn("holder", 3, holder_child)
    _wait_for(lambda: len(_slot_lines(lock_dir)) == 3, "the holder's 3 slot lines")
    _wait_for(holder_started.exists, "the holder's child to start")

    waiter = spawn("waiter", 2, _touch_child(tmp_path / "waiter-ran"), max_wait=1.5)
    assert waiter.wait() == 1
    output = waiter.output()
    assert (
        f"token budget: waiting for 2 of 4 tokens — held by: {TEST_SLUG}/holder (3)"
        in output
    )
    assert "gave up" in output
    assert not (tmp_path / "waiter-ran").exists()

    os.killpg(holder.process.pid, signal.SIGKILL)
    holder.wait()
    full = spawn("full", 4, _touch_child(tmp_path / "full-ran"), max_wait=0)
    assert full.wait() == 0, full.output()
    assert "waiting" not in full.output()
    assert (tmp_path / "full-ran").exists()


def test_sigint_while_queued_exits_130_and_releases(
    tmp_path: Path, lock_dir: Path, spawn: Callable[..., Runner]
) -> None:
    holder_child, _, _ = _marker_child(tmp_path, "holder")
    spawn("holder", 3, holder_child)
    _wait_for(lambda: len(_slot_lines(lock_dir)) == 3, "the holder's 3 slot lines")

    queued_marker = tmp_path / "queued-ran"
    queued = spawn("queued", 2, _touch_child(queued_marker))
    _wait_for(
        lambda: "waiting for 2 of 4 tokens" in queued.output(),
        "the queued runner's wait line",
    )
    queued.process.send_signal(signal.SIGINT)
    assert queued.wait() == 130, queued.output()
    assert not queued_marker.exists()
    assert "resolved capacity" not in queued.output()

    probe = spawn("probe", 1, _touch_child(tmp_path / "probe-ran"), max_wait=0)
    assert probe.wait() == 0, probe.output()
    assert "waiting" not in probe.output()


