def test_lock_dir_owned_by_another_uid_is_refused(
    tmp_path: Path,
    capacity_file: Path,
    lock_dir: Path,
    monkeypatch: pytest.MonkeyPatch,
    capsys: pytest.CaptureFixture[str],
) -> None:
    lock_dir.mkdir(mode=0o700)
    real_lstat = os.lstat
    foreign_uid = os.getuid() + 1

    def fake_lstat(path: str | os.PathLike[str], **kwargs: object) -> os.stat_result:
        result = real_lstat(path, **kwargs)
        if Path(str(path)) != lock_dir:
            return result
        fields = list(result)
        fields[4] = foreign_uid  # st_uid
        return os.stat_result(fields)

    monkeypatch.setattr(token_budget.os, "lstat", fake_lstat)
    marker = tmp_path / "ran"
    exit_code = main(_run_args(capacity_file, lock_dir, "1", _touch_child(marker)))
    monkeypatch.undo()
    assert exit_code == 1
    assert not marker.exists()
    err = capsys.readouterr().err
    assert err.startswith("token budget: ")
    assert f"uid {foreign_uid}" in err


