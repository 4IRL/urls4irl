@pytest.fixture
def spawn(
    tmp_path: Path, capacity_file: Path, lock_dir: Path
) -> Iterator[Callable[..., Runner]]:
    """Start runners in their own process group; kill every group on teardown."""
    runners: list[Runner] = []

    def start(
        name: str,
        tokens: int,
        child: list[str],
        max_wait: float | None = None,
        meminfo: Path | None = None,
        settle_seconds: float = 0,
    ) -> Runner:
        """No settle window unless a test asks for one: the contention cases
        predate it, and a 20 s default would only slow them down."""
        log = tmp_path / f"{name}.log"
        argv = [
            sys.executable,
            "-m",
            "scripts.token_budget",
            "run",
            "--capacity-file",
            str(capacity_file),
            "--lock-dir",
            str(lock_dir),
            "--meminfo",
            str(meminfo or capacity_file.with_name(MEMINFO_NAME)),
            "--cgroup",
            str(capacity_file.with_name(NO_CGROUP_NAME)),
            "--settle-seconds",
            str(settle_seconds),
            "--tokens",
            str(tokens),
            "--label",
            name,
        ]
        if max_wait is not None:
            argv += ["--max-wait", str(max_wait)]
        with log.open("wb") as log_handle:
            process = subprocess.Popen(
                [*argv, "--", *child],
                cwd=PROJECT_ROOT,
                env={**os.environ, "U4I_SLUG": TEST_SLUG},
                stdout=log_handle,
                stderr=subprocess.STDOUT,
                start_new_session=True,
                preexec_fn=_reset_sigint_to_default,
            )
        runner = Runner(process, log)
        runners.append(runner)
        return runner

    try:
        yield start
    finally:
        for runner in runners:
            if runner.process.poll() is None:
                try:
                    os.killpg(runner.process.pid, signal.SIGKILL)
                except ProcessLookupError:
                    pass
            try:
                runner.process.wait(timeout=SYNC_TIMEOUT_SECONDS)
            except subprocess.TimeoutExpired:
                runner.process.kill()


def _marker_child(
    tmp_path: Path, name: str, lifetime_seconds: float = SYNC_TIMEOUT_SECONDS
) -> tuple[list[str], Path, Path]:
    """A MARKER_CHILD that self-exits after `lifetime_seconds` if never released."""
    started = tmp_path / f"{name}-started"
    release = tmp_path / f"{name}-release"
    child = [
        sys.executable,
        "-c",
        MARKER_CHILD,
        str(started),
        str(release),
        str(lifetime_seconds),
    ]
    return child, started, release


def _touch_child(marker: Path) -> list[str]:
    return [sys.executable, "-c", f"open({str(marker)!r}, 'w').close()"]


def _exit_child(code: int) -> list[str]:
    return [sys.executable, "-c", f"import sys; sys.exit({code})"]


def _run_args(
    capacity_file: Path,
    lock_dir: Path,
    tokens: str,
    command: list[str],
    max_wait: str = "0",
    extra_flags: tuple[str, ...] = (),
    meminfo: Path | None = None,
) -> list[str]:
    return [
        "run",
        "--capacity-file",
        str(capacity_file),
        "--lock-dir",
        str(lock_dir),
        "--meminfo",
        str(meminfo or capacity_file.with_name(MEMINFO_NAME)),
        "--cgroup",
        str(capacity_file.with_name(NO_CGROUP_NAME)),
        *extra_flags,
        "--tokens",
        tokens,
        "--label",
        "unit-label",
        "--max-wait",
        max_wait,
        "--",
        *command,
    ]


def _hold_slots(lock_dir: Path, indexes: list[int], label: str) -> list[int]:
    """Lock slot files in this process (distinct open file descriptions)."""
    lock_dir.mkdir(mode=0o700, exist_ok=True)
    held: list[int] = []
    for index in indexes:
        descriptor = os.open(
            lock_dir / f"{token_budget.SLOT_PREFIX}{index}",
            os.O_RDWR | os.O_CREAT,
            0o600,
        )
        fcntl.flock(descriptor, fcntl.LOCK_EX | fcntl.LOCK_NB)
        os.write(
            descriptor,
            f"pid={os.getpid()} slug=other label={label} tokens={len(indexes)} "
            "since=2026-09-29T00:00:00+00:00\n".encode(),
        )
        held.append(descriptor)
    return held


def _release_slots(descriptors: list[int]) -> None:
    for descriptor in descriptors:
        os.close(descriptor)


