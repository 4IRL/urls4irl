"""Unit tests for the host-side test token runner (`scripts/token_budget.py`).

No Docker is used: every case runs against a fabricated capacity file under
`tmp_path`, and the contention cases use real `fcntl.flock` locks held by real
subprocesses, so they run identically on a laptop, inside the web container,
and on a CI runner. Every wait the harness itself performs is bounded by
SYNC_TIMEOUT_SECONDS, and every spawned runner is killed (its whole process
group) in fixture teardown, so a deadlock in `acquire()` fails instead of hangs.
"""

from __future__ import annotations

import fcntl
import io
import itertools
import os
import signal
import stat
import subprocess
import sys
import time
from collections.abc import Callable, Iterator
from pathlib import Path

import pytest

from scripts import token_budget
from scripts.token_budget import BudgetError, format_failure_block, main, read_budget

pytestmark = pytest.mark.unit

SYNC_TIMEOUT_SECONDS: int = 10
HARNESS_POLL_SECONDS: float = 0.05
PROJECT_ROOT: Path = Path(__file__).resolve().parents[2]
DECISION: str = "n_ui=2 n_int=4 binding=cpu usable_gb=9.6 spoke_max=4"
BUDGET: int = 4
TEST_SLUG: str = "tokentest"
# A child command that records when it started, then waits (bounded) for a
# release marker, so the test — not wall-clock timing — decides when it exits.
MARKER_CHILD: str = (
    "import pathlib, sys, time\n"
    "pathlib.Path(sys.argv[1]).write_text(str(time.time_ns()))\n"
    "deadline = time.monotonic() + float(sys.argv[3])\n"
    "while not pathlib.Path(sys.argv[2]).exists() and time.monotonic() < deadline:\n"
    "    time.sleep(0.02)\n"
)


def _write_capacity(path: Path, n_max: str = str(BUDGET)) -> Path:
    path.write_text(
        "# GENERATED by make capacity — DO NOT EDIT\n"
        f"# decision: {DECISION}\n"
        "U4I_N_UI=2\n"
        f"U4I_N_MAX={n_max}\n"
    )
    return path


def _wait_for(predicate: Callable[[], bool], description: str) -> None:
    deadline = time.monotonic() + SYNC_TIMEOUT_SECONDS
    while not predicate():
        if time.monotonic() >= deadline:
            pytest.fail(
                f"timed out after {SYNC_TIMEOUT_SECONDS}s waiting for {description}"
            )
        time.sleep(HARNESS_POLL_SECONDS)


def _read(path: Path) -> str:
    return path.read_text() if path.exists() else ""


def _slot_lines(lock_dir: Path) -> list[str]:
    return [
        line
        for slot in sorted(lock_dir.glob(f"{token_budget.SLOT_PREFIX}*"))
        for line in _read(slot).splitlines()
        if line.strip()
    ]


def _slot_fields(line: str) -> dict[str, str]:
    return dict(field.split("=", 1) for field in line.split())


class Runner:
    """A `python -m scripts.token_budget run …` subprocess logging to a file."""

    def __init__(self, process: subprocess.Popen[bytes], log: Path) -> None:
        self.process = process
        self.log = log

    def output(self) -> str:
        return _read(self.log)

    def wait(self) -> int:
        try:
            return self.process.wait(timeout=SYNC_TIMEOUT_SECONDS)
        except subprocess.TimeoutExpired:
            pytest.fail(
                f"runner did not exit within {SYNC_TIMEOUT_SECONDS}s:\n{self.output()}"
            )


def _reset_sigint_to_default() -> None:
    # A SIG_IGN inherited from the test process (e.g. a nohup'd pytest) would stop
    # the runner's Python from installing KeyboardInterrupt for SIGINT.
    signal.signal(signal.SIGINT, signal.SIG_DFL)


@pytest.fixture
def capacity_file(tmp_path: Path) -> Path:
    return _write_capacity(tmp_path / "capacity.env")


@pytest.fixture
def lock_dir(tmp_path: Path) -> Path:
    return tmp_path / "tokens"


@pytest.fixture
def spawn(
    tmp_path: Path, capacity_file: Path, lock_dir: Path
) -> Iterator[Callable[..., Runner]]:
    """Start runners in their own process group; kill every group on teardown."""
    runners: list[Runner] = []

    def start(
        name: str, tokens: int, child: list[str], max_wait: float | None = None
    ) -> Runner:
        log = tmp_path / f"{name}.log"
        argv = [
            sys.executable,
            "-m",
            "scripts.token_budget",
            "run",
            "--capacity-file",
            str(capacity_file),
            "--lock-dir",
            str(lock_dir),
            "--tokens",
            str(tokens),
            "--label",
            name,
        ]
        if max_wait is not None:
            argv += ["--max-wait", str(max_wait)]
        with log.open("wb") as log_handle:
            process = subprocess.Popen(
                [*argv, "--", *child],
                cwd=PROJECT_ROOT,
                env={**os.environ, "U4I_SLUG": TEST_SLUG},
                stdout=log_handle,
                stderr=subprocess.STDOUT,
                start_new_session=True,
                preexec_fn=_reset_sigint_to_default,
            )
        runner = Runner(process, log)
        runners.append(runner)
        return runner

    try:
        yield start
    finally:
        for runner in runners:
            if runner.process.poll() is None:
                try:
                    os.killpg(runner.process.pid, signal.SIGKILL)
                except ProcessLookupError:
                    pass
            try:
                runner.process.wait(timeout=SYNC_TIMEOUT_SECONDS)
            except subprocess.TimeoutExpired:
                runner.process.kill()


def _marker_child(tmp_path: Path, name: str) -> tuple[list[str], Path, Path]:
    started = tmp_path / f"{name}-started"
    release = tmp_path / f"{name}-release"
    child = [
        sys.executable,
        "-c",
        MARKER_CHILD,
        str(started),
        str(release),
        str(SYNC_TIMEOUT_SECONDS),
    ]
    return child, started, release


def _touch_child(marker: Path) -> list[str]:
    return [sys.executable, "-c", f"open({str(marker)!r}, 'w').close()"]


def _exit_child(code: int) -> list[str]:
    return [sys.executable, "-c", f"import sys; sys.exit({code})"]


def _run_args(
    capacity_file: Path,
    lock_dir: Path,
    tokens: str,
    command: list[str],
    max_wait: str = "0",
) -> list[str]:
    return [
        "run",
        "--capacity-file",
        str(capacity_file),
        "--lock-dir",
        str(lock_dir),
        "--tokens",
        tokens,
        "--label",
        "unit-label",
        "--max-wait",
        max_wait,
        "--",
        *command,
    ]


def _hold_slots(lock_dir: Path, indexes: list[int], label: str) -> list[int]:
    """Lock slot files in this process (distinct open file descriptions)."""
    lock_dir.mkdir(mode=0o700, exist_ok=True)
    held: list[int] = []
    for index in indexes:
        descriptor = os.open(
            lock_dir / f"{token_budget.SLOT_PREFIX}{index}",
            os.O_RDWR | os.O_CREAT,
            0o600,
        )
        fcntl.flock(descriptor, fcntl.LOCK_EX | fcntl.LOCK_NB)
        os.write(
            descriptor,
            f"pid={os.getpid()} slug=other label={label} tokens={len(indexes)} "
            "since=2026-09-29T00:00:00+00:00\n".encode(),
        )
        held.append(descriptor)
    return held


def _release_slots(descriptors: list[int]) -> None:
    for descriptor in descriptors:
        os.close(descriptor)


