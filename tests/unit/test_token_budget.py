class _RecordingDocker:
    """A docker runner that records each argv and answers from a script."""

    def __init__(self, *outputs: tuple[int, str]) -> None:
        self.outputs = list(outputs)
        self.calls: list[list[str]] = []

    def __call__(self, args: list[str]) -> subprocess.CompletedProcess[str]:
        self.calls.append(args)
        returncode, stdout = self.outputs.pop(0)
        return subprocess.CompletedProcess(["docker", *args], returncode, stdout, "")


