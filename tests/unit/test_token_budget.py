class _InterruptingSleep:
    """Advances FakeTime like its sleep, then raises KeyboardInterrupt (a Ctrl-C)
    on call number `interrupt_on`."""

    def __init__(self, fake_time: FakeTime, interrupt_on: int) -> None:
        self.fake_time = fake_time
        self.interrupt_on = interrupt_on
        self.calls = 0

    def __call__(self, seconds: float) -> None:
        self.calls += 1
        self.fake_time.sleep(seconds)
        if self.calls == self.interrupt_on:
            raise KeyboardInterrupt


