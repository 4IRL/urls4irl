def test_turnstile_holder_is_served_before_later_waiter(
    tmp_path: Path, lock_dir: Path, spawn: Callable[..., Runner]
) -> None:
    holder_child, _, holder_release = _marker_child(tmp_path, "holder")
    first_child, first_started, first_release = _marker_child(tmp_path, "first")
    second_child, second_started, second_release = _marker_child(tmp_path, "second")

    holder = spawn("holder", 3, holder_child)
    _wait_for(lambda: len(_slot_lines(lock_dir)) == 3, "the holder's 3 slot lines")
    first = spawn("first", 2, first_child)
    _wait_for(
        lambda: "waiting for 2 of 4 tokens" in first.output(),
        "the first waiter's wait line",
    )
    second = spawn("second", 1, second_child)
    _wait_for(
        lambda: "waiting for 1 of 4 tokens" in second.output(),
        "the second waiter's wait line",
    )
    assert f"{TEST_SLUG}/holder (3)" in second.output()
    assert f"{TEST_SLUG}/first (1)" in second.output()

    holder_release.touch()
    assert holder.wait() == 0, holder.output()
    _wait_for(first_started.exists, "the first waiter's child to start")
    _wait_for(second_started.exists, "the second waiter's child to start")

    # Each runner stamps `since=` as it locks a slot. The first waiter locks its
    # last slot while still holding the turnstile, and the second can lock
    # nothing until it gets the turnstile — so the first is served strictly
    # before the second. (Child start times are not compared: both children
    # start within one interpreter startup of each other, which is not ordered.)
    lines = [_slot_fields(line) for line in _slot_lines(lock_dir)]
    first_since = [fields["since"] for fields in lines if fields["label"] == "first"]
    second_since = [fields["since"] for fields in lines if fields["label"] == "second"]
    assert len(first_since) == 2
    assert len(second_since) == 1
    assert max(first_since) < second_since[0]

    first_release.touch()
    second_release.touch()
    assert first.wait() == 0, first.output()
    assert second.wait() == 0, second.output()


