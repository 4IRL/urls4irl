def test_acquire_heartbeats_then_gives_up(lock_dir: Path) -> None:
    held = _hold_slots(lock_dir, [0, 1, 2], "holder")
    ticks = itertools.count()

    def fake_clock() -> float:
        # Each call advances one heartbeat, so every poll pass is heartbeat-due.
        return float(next(ticks) * token_budget.HEARTBEAT_SECONDS)

    out = io.StringIO()
    try:
        with pytest.raises(BudgetError) as error:
            token_budget.acquire(
                lock_dir,
                2,
                BUDGET,
                "unit-label",
                TEST_SLUG,
                2 * token_budget.HEARTBEAT_SECONDS + 1,
                fake_clock,
                out,
            )
    finally:
        _release_slots(held)
    lines = out.getvalue().splitlines()
    assert lines[0] == (
        "token budget: waiting for 2 of 4 tokens — held by: other/holder (3)"
    )
    assert any(
        line.startswith("token budget: still waiting for 2 of 4 tokens (")
        for line in lines[1:]
    )
    assert "gave up" in str(error.value)


def test_stale_slot_is_skipped_in_best_effort_holders(
    tmp_path: Path,
    capacity_file: Path,
    lock_dir: Path,
    capsys: pytest.CaptureFixture[str],
) -> None:
    lock_dir.mkdir(mode=0o700)
    finished = subprocess.Popen([sys.executable, "-c", "pass"])
    finished.wait(timeout=SYNC_TIMEOUT_SECONDS)
    (lock_dir / f"{token_budget.SLOT_PREFIX}0").write_text(
        f"pid={finished.pid} slug=other label=ghost tokens=1 "
        "since=2026-09-29T00:00:00+00:00\n"
    )
    # Holding the turnstile forces the runner onto the best-effort (content) read.
    turnstile = os.open(
        lock_dir / token_budget.TURNSTILE_NAME, os.O_RDWR | os.O_CREAT, 0o600
    )
    held: list[int] = []
    marker = tmp_path / "ran"
    try:
        fcntl.flock(turnstile, fcntl.LOCK_EX | fcntl.LOCK_NB)
        held = _hold_slots(lock_dir, [1], "holder")
        exit_code = main(_run_args(capacity_file, lock_dir, "1", _touch_child(marker)))
    finally:
        _release_slots(held)
        os.close(turnstile)
    assert exit_code == 1
    assert not marker.exists()
    err = capsys.readouterr().err
    assert "token budget: waiting for 1 of 4 tokens — held by: other/holder (1)" in err
    assert "ghost" not in err


