from __future__ import annotations

import ast
from enum import IntEnum
from pathlib import Path

import pytest

from backend.api_common import error_codes_ts
from backend.api_common.error_codes_ts import (
    ERROR_CODE_ENUMS,
    generate_error_codes_ts,
)
from backend.splash.constants import (
    EmailValidationErrorCodes,
    ForgotPasswordErrorCodes,
)

pytestmark = pytest.mark.unit

REPO_ROOT = Path(__file__).resolve().parents[2]
HEADER = "// Generated by `flask openapi generate-error-codes` — DO NOT EDIT."


def _block(source: str, enum_name: str) -> str:
    """Slice one enum's text from its `export const` line to the next blank line."""
    start = source.index(f"export const {enum_name} = {{")
    end = source.find("\n\n", start)
    return source[start:] if end == -1 else source[start:end]


def test_header_present():
    """
    GIVEN the generator
    WHEN it renders the file
    THEN the autogenerated banner is present
    """
    assert generate_error_codes_ts().startswith(HEADER)


def test_every_member_of_every_enum_is_emitted():
    """
    GIVEN every enum in ERROR_CODE_ENUMS
    WHEN the file is rendered
    THEN each enum has its const, type and every member with the exact value
    """
    source = generate_error_codes_ts()
    for enum_cls in ERROR_CODE_ENUMS:
        name = enum_cls.__name__
        assert f"export const {name} = {{" in source
        block = _block(source, name)
        type_name = name.removesuffix("s")
        assert (
            f"export type {type_name} = (typeof {name})[keyof typeof {name}];" in block
        )
        assert "} as const;" in block
        for member in enum_cls:
            assert f"  {member.name}: {int(member.value)}," in block


def test_enum_blocks_sorted_by_class_name():
    """
    GIVEN the registry
    WHEN the file is rendered
    THEN blocks are in class-name order
    """
    source = generate_error_codes_ts()
    positions = [
        source.index(f"export const {name} = {{")
        for name in sorted(cls.__name__ for cls in ERROR_CODE_ENUMS)
    ]
    assert positions == sorted(positions)


def test_members_keep_definition_order():
    """
    GIVEN ForgotPasswordErrorCodes (which skips 2)
    WHEN the file is rendered
    THEN members keep definition order and 2 is absent
    """
    source = generate_error_codes_ts()
    block = _block(source, ForgotPasswordErrorCodes.__name__)
    assert block.index("INVALID_FORM_INPUT: 1") < block.index("EMAIL_SEND_FAILURE: 3")
    assert ": 2," not in block


def test_output_is_deterministic_and_independent_of_registry_order(
    monkeypatch: pytest.MonkeyPatch,
):
    """
    GIVEN the registry reversed
    WHEN the file is rendered twice
    THEN both outputs are identical to the original, sorted rendering
    """
    original = generate_error_codes_ts()
    assert generate_error_codes_ts() == original

    monkeypatch.setattr(
        error_codes_ts, "ERROR_CODE_ENUMS", tuple(reversed(ERROR_CODE_ENUMS))
    )
    assert generate_error_codes_ts() == original


def test_zero_value_is_emitted():
    """
    GIVEN EmailValidationErrorCodes.UNKNOWN_EXCEPTION == 0
    WHEN the file is rendered
    THEN it is emitted as 0
    """
    assert EmailValidationErrorCodes.UNKNOWN_EXCEPTION.value == 0
    block = _block(generate_error_codes_ts(), EmailValidationErrorCodes.__name__)
    assert "  UNKNOWN_EXCEPTION: 0," in block


def test_duplicate_class_names_raise(monkeypatch: pytest.MonkeyPatch):
    """
    GIVEN a registry with two classes sharing a __name__
    WHEN the file is rendered
    THEN ValueError is raised
    """

    first = IntEnum("DupErrorCodes", {"FIRST": 1})
    second = IntEnum("DupErrorCodes", {"SECOND": 2})

    monkeypatch.setattr(error_codes_ts, "ERROR_CODE_ENUMS", (first, second))
    with pytest.raises(ValueError, match="DupErrorCodes"):
        generate_error_codes_ts()


def test_members_emitted_in_definition_order_not_value_order(
    monkeypatch: pytest.MonkeyPatch,
):
    """
    GIVEN a synthetic enum defining LATE=5 before EARLY=1
    WHEN the file is rendered
    THEN LATE appears before EARLY
    """
    synthetic = IntEnum("XErrorCodes", {"LATE": 5, "EARLY": 1})
    monkeypatch.setattr(error_codes_ts, "ERROR_CODE_ENUMS", (synthetic,))
    block = _block(generate_error_codes_ts(), "XErrorCodes")
    assert block.index("LATE: 5") < block.index("EARLY: 1")


def test_class_name_not_ending_in_error_codes_raises(
    monkeypatch: pytest.MonkeyPatch,
):
    """
    GIVEN a registry class whose name does not end in ErrorCodes
    WHEN the file is rendered
    THEN ValueError is raised
    """
    bad = IntEnum("BadEnum", {"A": 1})
    monkeypatch.setattr(error_codes_ts, "ERROR_CODE_ENUMS", (bad,))
    with pytest.raises(ValueError, match="BadEnum"):
        generate_error_codes_ts()


def _module_path(file_path: Path) -> str:
    relative = file_path.relative_to(REPO_ROOT).with_suffix("")
    parts = relative.parts
    if parts[-1] == "__init__":
        parts = parts[:-1]
    return ".".join(parts)


def _is_int_enum_base(base: ast.expr) -> bool:
    if isinstance(base, ast.Name):
        return base.id == "IntEnum"
    if isinstance(base, ast.Attribute):
        return base.attr == "IntEnum"
    return False


def test_registry_lists_every_backend_error_code_enum():
    """
    GIVEN every `*ErrorCodes(IntEnum)` class defined under backend/ (parsed with ast)
    WHEN compared with ERROR_CODE_ENUMS
    THEN the sets are equal, so an unregistered new enum fails here
    """
    found: set[tuple[str, str]] = set()
    for py_file in (REPO_ROOT / "backend").rglob("*.py"):
        tree = ast.parse(py_file.read_text(encoding="utf-8"))
        for node in ast.walk(tree):
            if (
                isinstance(node, ast.ClassDef)
                and node.name.endswith("ErrorCodes")
                and any(_is_int_enum_base(base) for base in node.bases)
            ):
                found.add((_module_path(py_file), node.name))

    registered = {(cls.__module__, cls.__name__) for cls in ERROR_CODE_ENUMS}
    assert found == registered, (
        f"missing from ERROR_CODE_ENUMS: {sorted(found - registered)}; "
        f"registered but not found: {sorted(registered - found)}"
    )
