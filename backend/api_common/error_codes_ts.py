_ERROR_CODES_FILE_HEADER = """\
// Generated by `flask openapi generate-error-codes` — DO NOT EDIT.
// Source of truth: the backend `*ErrorCodes` IntEnums listed in backend/api_common/error_codes_ts.py
//
// One object per enum, named after the Python class, so member names that
// collide across enums never mix.
"""


def generate_error_codes_ts() -> str:
    """Render `frontend/types/error-codes.ts` from `ERROR_CODE_ENUMS`.

    Pure (reads only the registry). Blocks are sorted by class name, members keep
    definition order. Raises ValueError if two registry entries share a name.
    """
    names = [enum_cls.__name__ for enum_cls in ERROR_CODE_ENUMS]
    duplicates = sorted({name for name in names if names.count(name) > 1})
    if duplicates:
        raise ValueError(f"Duplicate error code enum names in registry: {duplicates}")

    blocks: list[str] = []
    for enum_cls in sorted(ERROR_CODE_ENUMS, key=lambda cls: cls.__name__):
        const_name = enum_cls.__name__
        if not const_name.endswith("ErrorCodes"):
            raise ValueError(
                f"Error code enum name must end in 'ErrorCodes': {const_name}"
            )
        type_name = const_name[:-1]
        lines = [f"export const {const_name} = {{"]
        for member_name, member in enum_cls.__members__.items():
            lines.append(f"  {member_name}: {int(member.value)},")
        lines.append("} as const;")
        lines.append(
            f"export type {type_name} = (typeof {const_name})[keyof typeof {const_name}];"
        )
        blocks.append("\n".join(lines))

    return _ERROR_CODES_FILE_HEADER + "\n" + "\n\n".join(blocks) + "\n"
